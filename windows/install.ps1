param(
    [switch]$ForceConfig,
    [switch]$SkipAutostart
)

$ErrorActionPreference = "Stop"

$repoDir = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$installDir = Join-Path $env:LOCALAPPDATA "pxpipe"
$binDir = Join-Path $env:USERPROFILE ".local\bin"
$setupDir = Join-Path $env:USERPROFILE ".config\pxpipe-setup"
$pxpipeConfigDir = Join-Path $env:USERPROFILE ".config\pxpipe"
$pxpipeStateDir = Join-Path $env:USERPROFILE ".pxpipe"

$nodeCmd = Get-Command node -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
if (-not $nodeCmd) {
    throw "Node.js is required (>= 22.15 recommended for Windows system CA export)."
}
$nodeVersionRaw = (& $nodeCmd.Source -p "process.versions.node").Trim()
$nodeVersionCore = $nodeVersionRaw -replace '[-+].*$', ''
$nodeVer = [version]$nodeVersionCore
if ($nodeVer -lt [version]"20.19.0") {
    throw "Node.js $nodeVersionRaw is too old. pxpipe requires >= 20.19.0 (22.15+ recommended on Windows)."
}
if ($nodeVer -lt [version]"22.15.0") {
    Write-Warning "Node.js $nodeVersionRaw detected. Upgrade to >= 22.15 so pxpipe warp can export Windows root certificates via tls.getCACertificates('system')."
}

$npmCmd = Get-Command npm -ErrorAction SilentlyContinue | Select-Object -First 1
if (-not $npmCmd) {
    throw "npm is required on PATH."
}

New-Item -ItemType Directory -Force -Path $installDir, $binDir, $setupDir, $pxpipeConfigDir, $pxpipeStateDir | Out-Null

Write-Host "[pxpipe-setup] Installing pxpipe-proxy@latest into $installDir..."
& $npmCmd.Source install --prefix $installDir pxpipe-proxy@latest
if ($LASTEXITCODE -ne 0) {
    throw "npm install pxpipe-proxy failed."
}

$cliJs = Join-Path $installDir "node_modules\pxpipe-proxy\bin\cli.js"

# Install pxpipe command shim (.cmd + .ps1) in %USERPROFILE%\.local\bin
@"
@echo off
setlocal
node "$cliJs" %*
"@ | Set-Content -Encoding Ascii -Path (Join-Path $binDir "pxpipe.cmd")

@"
& node "$cliJs" @args
exit `$LASTEXITCODE
"@ | Set-Content -Encoding UTF8 -Path (Join-Path $binDir "pxpipe.ps1")

Copy-Item -Force (Join-Path $repoDir "config\agents.json") (Join-Path $setupDir "agents.json")
Copy-Item -Force (Join-Path $repoDir "windows\pxpipe-wrap.ps1") (Join-Path $setupDir "pxpipe-wrap.ps1")
Copy-Item -Force (Join-Path $repoDir "windows\start-pxpipe.ps1") (Join-Path $setupDir "start-pxpipe.ps1")

$pxpipeConfigTarget = Join-Path $pxpipeConfigDir "config.json"
if ($ForceConfig -or -not (Test-Path $pxpipeConfigTarget)) {
    Copy-Item -Force (Join-Path $repoDir "config\pxpipe-config.json") $pxpipeConfigTarget
    Write-Host "[pxpipe-setup] Wrote $pxpipeConfigTarget"
} else {
    Write-Host "[pxpipe-setup] Keeping existing $pxpipeConfigTarget (use -ForceConfig to overwrite)"
}

function Test-WindowsAgentInstalled {
    param([string]$CommandName)
    $localBin = $binDir.ToLowerInvariant()
    $apps = Get-Command $CommandName -All -CommandType Application,ExternalScript -ErrorAction SilentlyContinue
    foreach ($app in $apps) {
        if (-not $app.Source) { continue }
        $lower = $app.Source.ToLowerInvariant()
        if ($lower.StartsWith($localBin) -and [IO.Path]::GetFileNameWithoutExtension($lower).StartsWith("p")) {
            continue
        }
        return $true
    }
    return $false
}

$psExe = if (Get-Command pwsh -ErrorAction SilentlyContinue) { "pwsh.exe" } else { "powershell.exe" }
$wrapScript = Join-Path $setupDir "pxpipe-wrap.ps1"
$manifest = Get-Content -Raw -Path (Join-Path $setupDir "agents.json") | ConvertFrom-Json

$aliasesPs1 = @(
    "# Generated by pxpipe-setup\windows\install.ps1 — do not edit manually"
)
$installedSummary = @()

foreach ($agent in $manifest.agents) {
    $cmdPath = Join-Path $binDir "$($agent.alias).cmd"
    if (Test-WindowsAgentInstalled -CommandName $agent.command) {
        @"
@echo off
setlocal
$psExe -NoProfile -ExecutionPolicy Bypass -File "$wrapScript" $($agent.command) %*
"@ | Set-Content -Encoding Ascii -Path $cmdPath

        $aliasesPs1 += "function $($agent.alias) { & `"$wrapScript`" $($agent.command) @args }"
        $installedSummary += "$($agent.alias) -> $($agent.command) $($agent.yoloFlags -join ' ')"
    } else {
        if (Test-Path $cmdPath) { Remove-Item -Force $cmdPath }
    }
}

$aliasesFile = Join-Path $setupDir "aliases.ps1"
$aliasesPs1 -join "`r`n" | Set-Content -Encoding UTF8 -Path $aliasesFile

# Ensure %USERPROFILE%\.local\bin is in User PATH
$userPath = [Environment]::GetEnvironmentVariable("Path", "User")
$pathParts = if ($userPath) { $userPath -split ";" | Where-Object { $_ } } else { @() }
if (-not ($pathParts | Where-Object { $_.TrimEnd("\") -ieq $binDir.TrimEnd("\") })) {
    $newUserPath = (@($binDir) + $pathParts) -join ";"
    [Environment]::SetEnvironmentVariable("Path", $newUserPath, "User")
    if (-not (($env:Path -split ";") | Where-Object { $_.TrimEnd("\") -ieq $binDir.TrimEnd("\") })) {
        $env:Path = "$binDir;$env:Path"
    }
    Write-Host "[pxpipe-setup] Added $binDir to User PATH"
}

# Wire aliases.ps1 into both PowerShell 7 and Windows PowerShell 5.1 profiles
function Update-PsProfile {
    param([string]$ProfilePath)
    $dir = Split-Path -Parent $ProfilePath
    New-Item -ItemType Directory -Force -Path $dir | Out-Null
    $startMarker = "# >>> pxpipe-setup >>>"
    $endMarker = "# <<< pxpipe-setup <<<"
    $snippet = "$startMarker`r`nif (Test-Path `"$aliasesFile`") { . `"$aliasesFile`" }`r`n$endMarker"
    $existing = if (Test-Path $ProfilePath) { Get-Content -Raw -Path $ProfilePath } else { "" }
    $pattern = "(?ms)\r?\n?$([regex]::Escape($startMarker)).*?$([regex]::Escape($endMarker))\r?\n?"
    $cleaned = ([regex]::Replace($existing, $pattern, "`r`n")).TrimEnd()
    $updated = if ($cleaned) { "$cleaned`r`n`r`n$snippet`r`n" } else { "$snippet`r`n" }
    Set-Content -Encoding UTF8 -Path $ProfilePath -Value $updated
}

$docsDir = [Environment]::GetFolderPath("MyDocuments")
Update-PsProfile -ProfilePath (Join-Path $docsDir "PowerShell\Microsoft.PowerShell_profile.ps1")
Update-PsProfile -ProfilePath (Join-Path $docsDir "WindowsPowerShell\Microsoft.PowerShell_profile.ps1")

# Start proxies now and register logon autostart
$startScript = Join-Path $setupDir "start-pxpipe.ps1"
& $startScript -Ports @(47821, 47822)

if (-not $SkipAutostart) {
    $taskName = "pxpipe-setup-autostart"
    $taskArg = "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$startScript`""
    try {
        $action = New-ScheduledTaskAction -Execute $psExe -Argument $taskArg
        $trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
        $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit (New-TimeSpan -Minutes 5)
        Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Settings $settings -Force | Out-Null
        Write-Host "[pxpipe-setup] Registered logon Scheduled Task: $taskName"
    } catch {
        Write-Warning "Scheduled Task registration failed ($($_.Exception.Message)); falling back to Startup VBS."
        $startupDir = [Environment]::GetFolderPath("Startup")
        $vbsPath = Join-Path $startupDir "pxpipe-setup.vbs"
        $vbsCmd = ("$psExe $taskArg").Replace('"', '""')
        @"
Set shell = CreateObject("WScript.Shell")
shell.Run "$vbsCmd", 0, False
"@ | Set-Content -Encoding Ascii -Path $vbsPath
        Write-Host "[pxpipe-setup] Wrote Startup launcher: $vbsPath"
    }
}

Write-Host "[pxpipe-setup] pxpipe version: $((& $nodeCmd.Source $cliJs --version).Trim())"
Write-Host "[pxpipe-setup] Dashboard: http://127.0.0.1:47821/"
Write-Host "[pxpipe-setup] Installed p-aliases:"
foreach ($item in $installedSummary) {
    Write-Host "  - $item"
}
